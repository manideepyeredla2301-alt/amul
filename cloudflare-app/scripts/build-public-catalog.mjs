import { copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, '..');
const repoRoot = path.resolve(appRoot, '..');
const source = JSON.parse(await readFile(path.join(repoRoot, 'catalog.json'), 'utf8'));
const sourceImages = path.join(repoRoot, 'images');
const publicImages = path.join(appRoot, 'public', 'images');
await mkdir(publicImages, { recursive: true });
const imageNames = new Set(await readdir(sourceImages));

function unitsPerBox(department, category, product) {
  const explicit = Number(product.unitsPerBox || 0);
  if (Number.isInteger(explicit) && explicit > 0) return explicit;
  const crateUnits = Number(product.unitsPerCase || 0);
  const pair = String(product.pack || product.description || '').match(/\((\d+)\s*[xX×]\s*(\d+)\)/);
  if (!pair) return crateUnits;
  if (department.id === 'frozen' && category.id === 'ice_creams') return Number(pair[1]);
  if (department.id === 'chocolates' || String(product.id) === 'DWRCP70') return Number(pair[2]);
  return crateUnits;
}

const departments = (source.departments || []).map((department) => ({
  id: String(department.id),
  name: String(department.name),
  categories: (department.categories || []).map((category) => ({
    id: String(category.id),
    name: String(category.name),
    groups: (category.groups || []).map((group) => ({
      id: String(group.id),
      name: String(group.name),
      products: (group.products || []).map((product) => {
        // imageId keeps the original photo when a product id was corrected to the Amul code.
        const imageName = `${product.imageId || product.id}.jpg`;
        return {
          id: String(product.id),
          name: String(product.name),
          description: String(product.description || ''),
          pack: String(product.pack || ''),
          unitsPerCase: Number(product.unitsPerCase || 0),
          unitsPerBox: unitsPerBox(department, category, product),
          image: imageNames.has(imageName) ? `/images/${imageName}` : '',
        };
      }),
    })),
  })),
}));

for (const imageName of imageNames) {
  if (/^[A-Za-z0-9_-]+\.jpg$/.test(imageName)) await copyFile(path.join(sourceImages, imageName), path.join(publicImages, imageName));
}

const productCount = departments.reduce((sum, department) => sum + department.categories.reduce((categorySum, category) => categorySum + category.groups.reduce((groupSum, group) => groupSum + group.products.length, 0), 0), 0);
await writeFile(path.join(appRoot, 'public', 'catalog-data.json'), `${JSON.stringify({ title: source.title, departments, productCount })}\n`);
const sqlText = (value) => `'${String(value ?? '').replaceAll("'", "''")}'`;
const seedRows = departments.flatMap((department) => department.categories.flatMap((category) => category.groups.flatMap((group) => group.products.map((product) =>
  `(${sqlText(`AMUL:${product.id}`)},${sqlText(product.id)},${sqlText(product.name)},${sqlText(group.name)},'PCS',0,0,0,0,1,'catalog-seed','catalog-v2',${sqlText(source.sourceLatestInvoiceDate || '')},CURRENT_TIMESTAMP)`
))));
const seedSql = `-- Generated by scripts/build-public-catalog.mjs. Existing live inventory always wins.\nINSERT OR IGNORE INTO inventory(product_id,sku,product_name,category,unit,stock_qty,reserved_qty,mrp_paise,selling_price_paise,active,source_device,snapshot_id,source_updated_at,synced_at) VALUES\n${seedRows.join(',\n')};\nINSERT INTO sync_state(key,value,updated_at) VALUES('catalog_seed','${JSON.stringify({ product_count: productCount, version: source.version || 1 }).replaceAll("'", "''")}',CURRENT_TIMESTAMP) ON CONFLICT(key) DO UPDATE SET value=excluded.value,updated_at=CURRENT_TIMESTAMP;\n`;
await writeFile(path.join(appRoot, 'migrations', '0004_seed_catalogue.sql'), seedSql);
console.log(`Built public catalogue with ${productCount} products and ${imageNames.size} images.`);
